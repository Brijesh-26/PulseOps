"""Roles, permissions and the authenticated principal."""

from __future__ import annotations

import enum
from dataclasses import dataclass


class Role(enum.StrEnum):
    INGEST = "ingest"
    VIEWER = "viewer"
    OPERATOR = "operator"
    APPROVER = "approver"
    ADMIN = "admin"


class Permission(enum.StrEnum):
    EVENTS_WRITE = "events:write"
    INCIDENTS_READ = "incidents:read"
    INCIDENTS_TRANSITION = "incidents:transition"
    INVESTIGATE = "investigations:run"
    PROPOSALS_CREATE = "proposals:create"
    PROPOSALS_DECIDE = "proposals:decide"
    AUDIT_READ = "audit:read"
    DEMO_ADMIN = "demo:admin"


_READ = {Permission.INCIDENTS_READ, Permission.AUDIT_READ}

ROLE_PERMISSIONS: dict[Role, frozenset[Permission]] = {
    Role.INGEST: frozenset({Permission.EVENTS_WRITE}),
    Role.VIEWER: frozenset(_READ),
    Role.OPERATOR: frozenset(
        _READ
        | {Permission.INVESTIGATE, Permission.PROPOSALS_CREATE, Permission.INCIDENTS_TRANSITION}
    ),
    # Approvers decide on proposals but cannot create them: separation of duties.
    Role.APPROVER: frozenset(_READ | {Permission.PROPOSALS_DECIDE}),
    Role.ADMIN: frozenset(Permission),
}

# Identity used for proposals generated by the AI investigator. It holds no
# roles, can never authenticate, and is therefore unable to approve anything.
AI_INVESTIGATOR_IDENTITY = "system:investigator"


@dataclass(frozen=True)
class Principal:
    name: str
    roles: frozenset[Role]

    @property
    def permissions(self) -> frozenset[Permission]:
        perms: set[Permission] = set()
        for role in self.roles:
            perms |= ROLE_PERMISSIONS[role]
        return frozenset(perms)

    def has(self, permission: Permission) -> bool:
        return permission in self.permissions
